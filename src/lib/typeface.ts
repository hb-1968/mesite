// verticals on cols 0/4 (or 2 for stem letters), horizontals on rows 4
// (top of x-height), 6 (middle), 8 (baseline). ascenders rows 0-3,
// descenders rows 9-10. x-height letters sit in rows 4-8.
// the 11 letters of "hunterbridges" are hand-authored in an editor;
// the rest follow the same rules.

